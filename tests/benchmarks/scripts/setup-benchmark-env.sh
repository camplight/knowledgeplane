#!/usr/bin/env bash
#
# Create benchmark env files from local ArangoDB state.
# - Finds first user in DB
# - Creates a dedicated benchmark workspace for that user
# - Ensures a usable API key exists
# - Prompts for OPENAI_API_KEY
# - Writes both .env.benchmark and .env at repo root
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../../.." && pwd)"
DB_URL="${ARANGO_URL:-http://localhost:8529}"
DB_NAME="${ARANGO_DB_NAME:-knowledgeplane}"
DB_USER="${ARANGO_USER:-root}"
DB_PASSWORD="${ARANGO_PASSWORD:-root}"
KP_API_URL_DEFAULT="${KP_API_URL:-http://localhost:8081}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

require_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo -e "${RED}Error:${NC} required command not found: $1"
    exit 1
  fi
}

require_cmd curl
require_cmd python3

echo -e "${BLUE}Setting up benchmark env files...${NC}"

# Verify ArangoDB connectivity early.
if ! curl -s --fail --connect-timeout 3 "${DB_URL}/_api/version" -u "${DB_USER}:${DB_PASSWORD}" >/dev/null; then
  echo -e "${RED}Error:${NC} Cannot connect to ArangoDB at ${DB_URL}."
  echo "Start local stack first (for example: npm run dev), then retry."
  exit 1
fi

cursor_endpoint="${DB_URL}/_db/${DB_NAME}/_api/cursor"

first_user_json="$(curl -s --fail -u "${DB_USER}:${DB_PASSWORD}" \
  -H "Content-Type: application/json" \
  -X POST "${cursor_endpoint}" \
  -d '{
    "query": "FOR u IN users SORT u.created_at ASC LIMIT 1 RETURN { _id: u._id, _key: u._key, username: u.username, email: u.email, api_key: u.api_key }"
  }')"

user_count="$(python3 -c 'import json,sys; d=json.load(sys.stdin); print(len(d.get("result", [])))' <<< "${first_user_json}")"
if [[ "${user_count}" -eq 0 ]]; then
  echo -e "${RED}Error:${NC} no users found in local DB."
  echo "Please login to your local KP instance first (http://localhost:3000) to create a user, then rerun this script."
  exit 1
fi

user_fields="$(
  python3 -c 'import json,sys; u=json.load(sys.stdin)["result"][0]; print(u.get("_id","")); print(u.get("username",""))' <<< "${first_user_json}"
)"
USER_ID="$(printf "%s\n" "${user_fields}" | sed -n '1p')"
USERNAME="$(printf "%s\n" "${user_fields}" | sed -n '2p')"

timestamp_iso="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
timestamp_slug="$(date -u +"%Y%m%d%H%M%S")"
workspace_key="$(python3 -c 'import uuid; print(uuid.uuid4())')"
workspace_id="workspaces/${workspace_key}"
workspace_slug="benchmark-${timestamp_slug}"
workspace_name="Benchmark Workspace ${timestamp_slug}"
workspace_rest_api_key="bench_$(python3 -c 'import secrets; print(secrets.token_hex(16))')"

workspace_doc="$(python3 - <<PY
import json
print(json.dumps({
  "_key": "${workspace_key}",
  "name": "${workspace_name}",
  "slug": "${workspace_slug}",
  "description": "Auto-created benchmark workspace",
  "created_by": "${USER_ID}",
  "rest_api_key": "${workspace_rest_api_key}",
  "rest_api_key_created_by": "${USER_ID}",
  "rest_api_key_created_at": "${timestamp_iso}",
  "created_at": "${timestamp_iso}",
  "updated_at": "${timestamp_iso}"
}))
PY
)"

curl -s --fail -u "${DB_USER}:${DB_PASSWORD}" \
  -H "Content-Type: application/json" \
  -X POST "${DB_URL}/_db/${DB_NAME}/_api/document/workspaces" \
  -d "${workspace_doc}" >/dev/null

member_doc="$(python3 - <<PY
import json
print(json.dumps({
  "workspace_id": "${workspace_id}",
  "user_id": "${USER_ID}",
  "role": "owner",
  "created_at": "${timestamp_iso}",
  "updated_at": "${timestamp_iso}"
}))
PY
)"

curl -s --fail -u "${DB_USER}:${DB_PASSWORD}" \
  -H "Content-Type: application/json" \
  -X POST "${DB_URL}/_db/${DB_NAME}/_api/document/workspace_members" \
  -d "${member_doc}" >/dev/null

# Use workspace REST key for benchmark calls.
# This key is guaranteed to be scoped to the workspace we just created.
KP_API_KEY_VALUE="${workspace_rest_api_key}"

echo ""
echo "Enter OPENAI_API_KEY for benchmarks (input hidden)."
echo "Leave empty if you want to fill it later."
read -r -s -p "OPENAI_API_KEY: " OPENAI_API_KEY_INPUT
echo ""

env_content="$(cat <<EOF
# KnowledgePlane benchmark environment
# Generated by tests/benchmarks/scripts/setup-benchmark-env.sh
# DO NOT COMMIT REAL CREDENTIALS

export KP_API_URL="${KP_API_URL_DEFAULT}"
export ARANGO_URL="${DB_URL}"

export KP_WORKSPACE_ID="${workspace_id}"
export KP_USER_ID="${USER_ID}"
export KP_API_KEY="${KP_API_KEY_VALUE}"

export OPENAI_API_KEY="${OPENAI_API_KEY_INPUT}"
EOF
)"

printf "%s\n" "${env_content}" > "${ROOT_DIR}/.env.benchmark"
printf "%s\n" "${env_content}" > "${ROOT_DIR}/.env"

echo ""
echo -e "${GREEN}Done.${NC} Wrote:"
echo "  - ${ROOT_DIR}/.env.benchmark"
echo "  - ${ROOT_DIR}/.env"
echo ""
echo "Created workspace: ${workspace_id}"
echo "Using user: ${USER_ID} (${USERNAME:-unknown})"
echo ""
if [[ -z "${OPENAI_API_KEY_INPUT}" ]]; then
  echo -e "${YELLOW}Note:${NC} OPENAI_API_KEY is empty. Fill it before running benchmarks that require embeddings."
fi
